#define __Require(c, l) do { if (!(c)) goto l; } while (0)
#define __Require_Action(c, l, a) do { if (!(c)) { { a; } goto l; } } while (0)
#define __Require_noErr(c, l) do { if ((c) != 0) goto l; } while (0)
#define __Require_noErr_Action(c, l, a) do { if ((c) != 0) { { a; } goto l; } } while (0)
#define require(c, l) __Require(c, l)
#define require_action(c, l, a) __Require_Action(c, l, a)
#define require_noerr(c, l) __Require_noErr(c, l)
#define require_quiet(c, l) __Require(c, l)
#define __Require_Quiet(c, l) __Require(c, l)
