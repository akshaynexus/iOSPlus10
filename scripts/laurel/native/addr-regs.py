#!/usr/bin/env python3
"""addr-regs.py A6XX_XML [--header]: the a6xx registers that hold a GPU address, read from Mesa's a6xx.xml: reg64 of type waddress or address, the private memory bases and the bindless bases (those two have no type in the file), in the A6XX variant.
Without --header: "HEX NAME" lines (scripts/laurel/native/stream-check.py reads them this way). With --header: the C table userland/laurel/metal-native/winsys/nw_addr_regs.h.
scripts/laurel/native/test.sh checks that the file in git is what this prints. Run with python3 -I."""
import re
import sys
import xml.etree.ElementTree as ET

ADDRESS_TYPES = {"waddress", "address"}


def variant_has_a6xx(v):
    """variants="A6XX", "A6XX-", "A6XX-A7XX": A6XX on. "A7XX", "A7XX-": off. "" inherits."""
    if not v:
        return True
    for part in v.replace(",", " ").split():
        if part.startswith("A6XX") or part.startswith("A5XX-") or part.startswith("A2XX-"):
            return True
    return False


def strip(tag):
    return tag.split("}")[-1]


def walk(node, base, stride_path, prefix, out):
    for c in node:
        t = strip(c.tag)
        if not variant_has_a6xx(c.get("variants", "")):
            continue
        if t == "array":
            off = int(c.get("offset") or c.get("index") or "0", 0)
            n = int(c.get("length", "1"), 0)
            st = int(c.get("stride", "1"), 0)
            for i in range(n):
                walk(c, base + off + i * st, stride_path, f"{prefix}{c.get('name')}[{i}].", out)
        elif t == "reg64" and (c.get("type") in ADDRESS_TYPES or "PVT_MEM_ADDR" in c.get("name") or "BINDLESS_BASE" in prefix):
            out[base + int(c.get("offset"), 0)] = prefix + c.get("name")


root = ET.parse(sys.argv[1]).getroot()
regs = {}
for d in root:
    if strip(d.tag) == "domain" and d.get("name") == "A6XX":
        walk(d, 0, 0, "", regs)
if "--header" in sys.argv:
    print("/* SPDX-License-Identifier: MIT */")
    print("/* Generated by scripts/laurel/native/addr-regs.py from Mesa 25.0.7 src/freedreno/registers/adreno/a6xx.xml (MIT): every a6xx register that holds a GPU address. Do not edit. */")
    print("static const uint16_t nw_addr_regs[] = {")
    for r in sorted(regs):
        print(f"\t{r:#06x}, /* {regs[r]} */")
    print("};")
else:
    for r in sorted(regs):
        print(f"{r:04x} {regs[r]}")
