#!/usr/bin/env python3
"""Write the Mi A3 12377 base patches from the dev tree (scripts/laurel/ios26-series-tree.sh --dev, then edits).

    scripts/laurel/ios26-base-refresh.py [XNU_TREE]

GROUPS below names the files each base patch owns. For each file: git diff of the tree against 12377 + base 0001 (a
new file: against nothing). patches/laurel/xnu-12377/owned.txt gets one line per file with the series patches that
change it, so a NEW series patch for an owned file is an ERROR in apply-series.py until its change is ported here.
"""
import re
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
P = REPO / "patches" / "laurel" / "xnu-12377"
sys.path.insert(0, str(REPO / "scripts" / "laurel"))
GROUPS = {
    "0002-sweet-machine-config": ("machine config", """config/MASTER.arm64.sweet config/Private.arm64.exports config/Private.exports
        makedefs/MakeInc.def pexpert/pexpert/arm64/Makefile pexpert/pexpert/arm64/board_config.h"""),
    "0003-sweet-machine-layer": ("Kryo 260 machine layer: start.s, early console marks, SMP reset data, sleh includes", """osfmk/arm/arm_init.c
        osfmk/arm64/arm_vm_init.c osfmk/arm64/caches_asm.s osfmk/arm64/cpu.c osfmk/arm64/sleh.c osfmk/arm64/start.s
        pexpert/pexpert/arm/protos.h"""),
    "0004-sweet-platform-console": ("framebuffer serial console, console log tee, IORTC wait, boot trace", """pexpert/arm/pe_serial.c
        osfmk/console/serial_console.c osfmk/kern/startup.c iokit/Kernel/IOStartIOKit.cpp"""),
    "0005-sweet-core": ("kernel PRNG without the corecrypto kext, kmem random, jetsam limit, zalloc and shared region guards", """osfmk/prng/prng_random.c
        osfmk/vm/vm_map_store.c bsd/kern/kern_memorystatus.c osfmk/kern/zalloc.c osfmk/vm/vm_shared_region.c
        osfmk/vm/vm_page.h osfmk/vm/vm_resident.c osfmk/kern/sched_clutch.c"""),
}
HEADERS = {}


def main():
    owned_only = "--owned-only" in sys.argv
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    tree = Path(args[0] if args else REPO / "out/laurel-kernel-ios26/src/xnu")
    def git(*a):
        return subprocess.run(["git", "-C", str(tree), *a], capture_output=True, text=True, encoding="latin-1", check=True).stdout
    base = "" if owned_only else git("log", "--format=%h", "-n1", "--grep=base 0001-non-apple").strip()
    # series patches per file
    import importlib.util
    spec = importlib.util.spec_from_file_location("prof", REPO / "scripts" / "laurel" / "ios26-series.py")
    prof = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(prof)
    touch = {}
    spec2 = importlib.util.spec_from_file_location("applyseries", REPO / "scripts" / "ios26" / "apply-series.py")
    tool = importlib.util.module_from_spec(spec2)
    spec2.loader.exec_module(tool)
    for p in prof.series():
        for s in tool.parse(p.read_text(encoding="latin-1"))[1]:
            touch.setdefault(s.path, set()).add(p.name.split("-")[0])
    owned = []
    for name, (what, files) in GROUPS.items():
        files = files.split()
        if owned_only:
            for f in files:
                owned.append(f"{f} {name[:4]} {' '.join(sorted(touch.get(f, [])))}")
            continue
        diff = git("diff", "--no-color", "--no-renames", base, "--", *files)
        missing = [f for f in files if f"b/{f} " not in diff and f"b/{f}\n" not in diff]
        if missing:
            raise SystemExit(f"{name}: no change in {missing}")
        out = P / (name + ".patch")
        prev_head = ""
        if out.exists():
            prev_head = out.read_text(encoding="latin-1").split("diff --git", 1)[0]
        head = prev_head or f"From: iOSPlus10 Mi A3 ios26 port\nSubject: [PATCH] {name}: {what}\n\nGenerated by scripts/laurel/ios26-base-refresh.py.\n\n"
        out.write_text(head + diff, encoding="latin-1")
        print(f"{out.name}: {len(files)} files, {diff.count(chr(10))} lines")
        for f in files:
            owned.append(f"{f} {name[:4]} {' '.join(sorted(touch.get(f, [])))}")
    if not owned_only:
        # everything else changed since the end of the series: the post patch (12377 API of files the series creates)
        end = git("log", "--format=%h", "-n1", "--grep=^series end$").strip()
        all_owned = [o.split()[0] for o in owned]
        changed = [f for f in git("diff", "--name-only", "--no-renames", end).split() if f not in all_owned and not f.startswith("BUILD/")]
        (P / "post").mkdir(exist_ok=True)
        out = P / "post" / "9000-series-12377-api.patch"
        diff = git("diff", "--no-color", "--no-renames", end, "--", *changed) if changed else ""
        out.write_text("From: iOSPlus10 Mi A3 ios26 port\nSubject: [PATCH] 12377 API of files the series creates\n\nGenerated by scripts/laurel/ios26-base-refresh.py from the dev tree.\n\n" + diff, encoding="latin-1")
        print(f"{out.name}: {len(changed)} files, {diff.count(chr(10))} lines")
    (P / "owned.txt").write_text("# file, base patch, series patches whose change of that file the base holds (ios26-base-refresh.py)\n" + "\n".join(owned) + "\n")


if __name__ == "__main__":
    main()
