#!/usr/bin/env python3
"""Make a headers-only KDKROOT for xnu-12377 from a remote Kernel Debug Kit, without a 1.2 GB download.

  scripts/ios26/kdk-headers.py [--url URL] OUTPUT

xnu-12377 includes CoreEntitlements/V2, TrustCache, CodeSignature and TrustedExecutionMonitor headers that are not in
its source. Apple ships them in the KDK (KDK_SDK.pkg: Kernel.framework/PrivateHeaders/platform; KDK.pkg:
System/Library/KernelSupport/CoreEntitlements/V2/Kernel.h). OUTPUT gets only those headers, in the KDK layout, so
KDKROOT=OUTPUT adds them to the include path and nothing else (no KernelSupport archives in the link).

macOS: hdiutil attaches the remote disk image over HTTP (range reads). The xar TOC gives the payload offsets.
KDK_SDK.pkg/Payload is 140 KB (28 headers). Kernel.h (the CEKernelAPI_t table that AMFI hands to xnu) is in
KDK.pkg/Payload (1.1 GB of kernels and kexts). Default: we write our own Kernel.h from the V2 API.h/Acceleration.h
prototypes (one function pointer per CE* function, typed with __typeof__). That is enough for NEGRONI: the table is
only filled by our own AMFI stand-in, never by Apple's AMFI kext. --apple-kernel-h streams KDK.pkg/Payload
(pbzx -> cpio, nothing written to disk) until Apple's Kernel.h is found. Linux: give --dmg FILE (7z extracts the pkg).

Based on UniXNU scripts/kdk-headers.py (BSD-2-Clause-Patent, Copyright (c) 2026, UniXNU contributors); changed for
the HTTP mount and the early stop. Output is Apple content: never commit it (out/ is git-ignored).
"""
import argparse
import lzma
import shutil
import struct
import subprocess
import sys
import tempfile
import urllib.request
import xml.etree.ElementTree as ElementTree
import zlib
from pathlib import Path

DEFAULT_URL = ('https://github.com/dortania/KdkSupportPkg/releases/download/25F84/'
               'Kernel_Debug_Kit_26.5.2_build_25F84.dmg')
PLATFORM = 'System/Library/Frameworks/Kernel.framework/Versions/A/PrivateHeaders/platform/'
WANTED = {
    'KDK_SDK.pkg/Payload': (tuple(PLATFORM + n + '/' for n in
                                  ('CoreEntitlements', 'TrustCache', 'CodeSignature', 'TrustedExecutionMonitor')),
                            None),
}
APPLE_KERNEL_H = {
    # stop after this directory: the rest of the 1.1 GB payload is kernels and kexts
    'KDK.pkg/Payload': (('System/Library/KernelSupport/CoreEntitlements/',), 'System/Library/KernelSupport/CoreEntitlements/'),
}
KERNEL_H = 'System/Library/KernelSupport/CoreEntitlements/V2/Kernel.h'


def synthesize_kernel_h(output):
    """Our CEKernelAPI_t: a function pointer per CE* prototype in V2/API.h and V2/Acceleration.h."""
    import re
    v2 = output / PLATFORM / 'CoreEntitlements/V2'
    names = []
    for header in ('API.h', 'Acceleration.h'):
        names += re.findall(r'^(CE[A-Z][A-Za-z0-9]*)\(', (v2 / header).read_text(), re.M)
    members = '\n'.join(f'    __typeof__(&{n}) {n[2].lower()}{n[3:]};' for n in dict.fromkeys(names))
    target = output / KERNEL_H
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(f'''/* Generated by iOSPlus10 scripts/ios26/kdk-headers.py (not Apple's file).
 * CEKernelAPI_t: the CoreEntitlements V2 function table that the AMFI implementation registers with
 * amfi_core_entitlements_register(). Member = CE<Name> -> <name> with a lowercase first letter. */
#pragma once
#include <CoreEntitlements/V2/API.h>
#include <CoreEntitlements/V2/Acceleration.h>
typedef struct CEKernelAPI {{
{members}
}} CEKernelAPI_t;
''')
    print(f'kdk-headers: wrote our {KERNEL_H} ({len(dict.fromkeys(names))} members)', flush=True)


def xar_entries(handle):
    magic, header_size, _, toc_packed, _, _ = struct.unpack('>4sHHQQI', handle.read(28))
    if magic != b'xar!':
        sys.exit('not a xar archive')
    handle.seek(header_size)
    toc = ElementTree.fromstring(zlib.decompress(handle.read(toc_packed)))
    heap, entries = header_size + toc_packed, {}

    def walk(node, prefix):
        for item in node.findall('file'):
            path = prefix + item.findtext('name')
            data = item.find('data')
            if data is not None:
                entries[path] = (heap + int(data.findtext('offset')), int(data.findtext('length')),
                                 data.find('encoding').get('style'))
            walk(item, path + '/')
    walk(toc.find('toc'), '')
    return entries


def pbzx_chunks(handle, length):
    end = handle.tell() + length
    if handle.read(4) != b'pbzx':
        sys.exit('payload is not pbzx')
    handle.read(8)
    while handle.tell() < end:
        _, size = struct.unpack('>QQ', handle.read(16))
        chunk = handle.read(size)
        yield lzma.decompress(chunk) if chunk.startswith(b'\xfd7zXZ\x00') else chunk


class Stream:
    def __init__(self, chunks):
        self.chunks, self.buffer, self.pos = chunks, bytearray(), 0

    def read(self, size):
        while len(self.buffer) - self.pos < size:
            chunk = next(self.chunks, None)
            if chunk is None:
                sys.exit('payload ends inside a cpio record')
            del self.buffer[:self.pos]
            self.pos = 0
            self.buffer += chunk
        data = bytes(self.buffer[self.pos:self.pos + size])
        self.pos += size
        return data


def extract_cpio(stream, prefixes, stop_after, output):
    count, seen = 0, False
    while True:
        header = stream.read(76)
        if header[:6] != b'070707':
            sys.exit('payload is not an odc cpio archive')
        mode = int(header[18:24], 8)
        name_size, file_size = int(header[59:65], 8), int(header[65:76], 8)
        name = stream.read(name_size)[:-1].decode().removeprefix('./')
        data = stream.read(file_size)
        if name == 'TRAILER!!!':
            return count
        inside = name.startswith(prefixes)
        if mode & 0o170000 == 0o100000 and inside:
            target = output / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(data)
            count += 1
        if stop_after:
            if name.startswith(stop_after):
                seen = True
            elif seen:
                return count


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--url', default=DEFAULT_URL)
    parser.add_argument('--dmg', type=Path, help='local disk image instead of --url')
    parser.add_argument('--apple-kernel-h', action='store_true',
                        help="stream KDK.pkg/Payload (up to 1.1 GB over the network) for Apple's Kernel.h")
    parser.add_argument('output', type=Path)
    args = parser.parse_args()
    wanted = dict(WANTED, **(APPLE_KERNEL_H if args.apple_kernel_h else {}))
    identity = f'{(args.dmg.name if args.dmg else args.url.rsplit("/", 1)[-1])}\n'
    stamp = args.output / '.kdk-headers'
    if stamp.is_file() and stamp.read_text() == identity:
        print(f'kdk-headers: {args.output} is up to date')
        return
    if args.output.exists():
        shutil.rmtree(args.output)
    with tempfile.TemporaryDirectory() as temporary:
        work = Path(temporary)
        mount = work / 'mnt'
        mount.mkdir()
        if args.dmg and sys.platform != 'darwin':
            subprocess.run(['7z', 'e', '-y', f'-o{work}', args.dmg, '*/KernelDebugKit.pkg', '-r'], check=True)
            pkg, attached = work / 'KernelDebugKit.pkg', False
        else:
            source = str(args.dmg.resolve()) if args.dmg else \
                urllib.request.urlopen(urllib.request.Request(args.url, method='HEAD'), timeout=60).geturl()
            subprocess.run(['hdiutil', 'attach', '-nobrowse', '-readonly', '-mountpoint', mount, source],
                           check=True, stdout=subprocess.DEVNULL)
            attached = True
            pkg = next(mount.rglob('KernelDebugKit.pkg'))
        try:
            with open(pkg, 'rb') as handle:
                entries = xar_entries(handle)
                for payload, (prefixes, stop_after) in wanted.items():
                    offset, length, encoding = entries[payload]
                    if encoding != 'application/octet-stream':
                        sys.exit(f'{payload}: unexpected xar encoding {encoding}')
                    handle.seek(offset)
                    count = extract_cpio(Stream(pbzx_chunks(handle, length)), prefixes, stop_after, args.output)
                    if not count:
                        sys.exit(f'{payload}: none of {prefixes} found')
                    print(f'kdk-headers: {payload}: {count} headers', flush=True)
        finally:
            if attached:
                subprocess.run(['hdiutil', 'detach', '-force', mount], check=False, stdout=subprocess.DEVNULL)
    if not args.apple_kernel_h:
        synthesize_kernel_h(args.output)
    stamp.write_text(identity)


if __name__ == '__main__':
    main()
