/*
 * negronigl: Mesa freedreno GLES behind iOS's EAGLContext, for CoreAnimation's OpenGL ES renderer
 * in backboardd. Internal interfaces between the files:
 *
 *   negronigl.c   gallium screen (freedreno over the msm emulation, else softpipe), GLES contexts,
 *                 self tests, load hook (the dylib only)
 *   sw_winsys.c   softpipe's winsys: memory and IOSurface display targets
 *   eagl.c        EAGLContext methods, the GLI context {rctx, disp[]}, hand-written GLI slots
 *   plugin/       NegroniGL.bundle: the GLD renderer plugin libGFXShared loads (gld.c) and the GLI
 *                 entry points it puts in OpenGLES's table (gli.c); docs/gpu-userland.md
 *   shaders.c     shader source rewrites (rectangle textures, framebuffer fetch, CA helpers)
 *   surface.c     IOSurfaces as texture storage (kernel import -> pipe_resource -> EGLImage)
 *   gli_dispatch.c  generated by gen-gli.py from gli-slots.txt
 *   drm/          libdrm + msm DRM over RedwoodGPU (ngl_abi.h: the kernel ABI)
 *
 * Design after ios-sailfish tools/sweetgl (sweetgl.c, eagl.c, sweet_drm.c) and HackiOS
 * userland/src/eagl.c (MIT); the code is ours, adapted pieces name their source.
 */
