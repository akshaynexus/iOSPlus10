/* GLI: CA calls disp[slot](rctx, gl arguments...) on the table from -getMacroContextPrivate */
#define NGL_SLOTS 1036
#define NGL_GL_TEXTURE_RECTANGLE 0x84F5
#define NGL_UNITS 16
#define NGL_FBFETCH_UNIT 15
#define NGL_NAMES 8192                  /* texture / program / shader names tracked in tables */

struct ngl_copy {                       /* a texture that holds a CPU copy of an IOSurface */
	IOSurfaceRef surface;
	uint32_t seed;
	GLenum format, type;
};

struct ngl_rect_prog { GLuint program; GLint scale, sampler; };

/* per GL context: shadows of state that Apple's GL has and Mesa's GLES has not */
struct ngl_state {
	GLuint unit_2d[NGL_UNITS], unit_rect[NGL_UNITS], unit_held[NGL_UNITS];
	uint16_t tex_w[NGL_NAMES], tex_h[NGL_NAMES];
	uint8_t tex_argb[NGL_NAMES];
	struct ngl_copy copies[NGL_NAMES];
	uint8_t shader_kind[NGL_NAMES];          /* bit 0: rect sampler, bit 1: emulated fbfetch */
	char rect_sampler[NGL_NAMES][24];        /* (only for shaders with bit 0) */
	struct ngl_rect_prog rect_prog[NGL_NAMES]; /* by program name; .program == 0: none */
	GLint fbf_sampler[NGL_NAMES], fbf_scale[NGL_NAMES];   /* location + 1, 0: none */
	uint16_t prog_units[NGL_NAMES];          /* bit u: a sampler reads unit u; bit 15: known */
};

struct ngl_gli {
	void *rctx;                     /* = this; CA reads {rctx, disp[]} */
	void *disp[NGL_SLOTS];
	void *eagl;                     /* the EAGLContext (id); NULL in the GLI-plugin path */
	unsigned api;
	struct ngl_ctx *ctx;
	struct ngl_state *st;
	/* GLI-plugin fields (plugin/gli_context.c, gli_view.c); unused by the dylib EAGL shim */
	void *shared;                   /* gld shared-state pointer = the EAGLSharegroup, NULL if none */
	void *view;                     /* the drawable bound by gliBindViewES, NULL if none */
	IOSurfaceRef view_surface;      /* its IOSurface, retained; released on unbind/destroy */
	unsigned view_colorformat;
};

extern __thread struct ngl_gli *ngl_cur;
void ngl_bind(struct ngl_gli *g);
#define NGL_CUR(r) do { if (__builtin_expect(ngl_cur != (struct ngl_gli *)(r), 0)) ngl_bind(r); } while (0)

extern int ngl_check_errors;            /* NEGRONIGL_GLERR=1 */
void ngl_post(int slot);
#define NGL_POST(i) do { if (__builtin_expect(ngl_check_errors, 0)) ngl_post(i); } while (0)
void ngl_unsupported(int slot);

